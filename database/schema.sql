-- Cada cuenta administradora crea un NEGOCIO; todo lo demás pertenece a un negocio.
create table public.negocios (
  id         bigint generated by default as identity primary key,
  nombre     varchar(80) not null,
  creado_en  timestamptz not null default now()
);

create table public.usuarios (
  id          bigint generated by default as identity primary key,
  negocio_id  bigint not null references public.negocios (id) on delete cascade,
  usuario     varchar(100) not null,
  email       varchar(100) not null,
  contrasena  varchar(255) not null,               -- hash bcrypt generado con password_hash()
  rol         varchar(10)  not null default 'empleado' check (rol in ('admin', 'empleado')),
  activo      boolean      not null default true,  -- desactivar en vez de borrar (conserva el historial)
  creado_en   timestamptz  not null default now(),
  unique (id, negocio_id)                           -- permite la clave foránea compuesta de ventas
);
-- Usuario y correo únicos sin distinguir mayúsculas (antes solo se validaba en el código PHP).
create unique index usuarios_usuario_uq on public.usuarios (lower(usuario));
create unique index usuarios_email_uq   on public.usuarios (lower(email));
create index usuarios_negocio_idx       on public.usuarios (negocio_id);

create table public.productos (
  id          bigint generated by default as identity primary key,
  negocio_id  bigint not null references public.negocios (id) on delete cascade,
  nombre      varchar(100) not null,
  categoria   varchar(50)  not null,
  precio      numeric(10,2) not null check (precio >= 0),
  stock       integer       not null default 0 check (stock >= 0),  -- la base impide stock negativo
  activo      boolean       not null default true,
  unique (id, negocio_id)
);
create index productos_negocio_idx on public.productos (negocio_id, activo);
-- No se permiten dos productos con el mismo nombre en un negocio (sin distinguir mayúsculas),
-- estén activos o desactivados.
create unique index productos_negocio_nombre_uq on public.productos (negocio_id, lower(nombre));

-- Cada fila es una línea de venta (un producto dentro de un cobro). Las líneas de un mismo cobro
-- comparten la misma fecha y el mismo vendedor.
create table public.ventas (
  id_venta         bigint generated by default as identity primary key,
  negocio_id       bigint not null references public.negocios (id) on delete cascade,
  id_producto      bigint not null,
  id_usuario       bigint not null,
  cantidad         integer       not null check (cantidad > 0),
  precio_unitario  numeric(10,2) not null check (precio_unitario >= 0),  -- precio al momento de vender
  fecha            timestamptz   not null default now(),
  metodo_pago      varchar(20)   not null default 'efectivo'
                   check (metodo_pago in ('efectivo', 'nequi', 'transferencia', 'llave')),
  -- Claves compuestas: garantizan que el producto y el vendedor sean del MISMO negocio que la venta.
  foreign key (id_producto, negocio_id) references public.productos (id, negocio_id),
  foreign key (id_usuario,  negocio_id) references public.usuarios  (id, negocio_id)
);
create index ventas_negocio_fecha_idx on public.ventas (negocio_id, fecha desc);
create index ventas_producto_idx      on public.ventas (id_producto);
create index ventas_usuario_idx       on public.ventas (id_usuario);

-- ---------------------------------------------------------------------
-- SEGURIDAD
-- La app se conecta desde el servidor (PHP) con el usuario de la base de datos.
-- Se activa RLS sin políticas: así la API pública de Supabase (claves "anon"/"authenticated",
-- que viajan al navegador) NO puede leer ni escribir nada. Solo el servidor tiene acceso.
-- ---------------------------------------------------------------------
alter table public.negocios  enable row level security;
alter table public.usuarios  enable row level security;
alter table public.productos enable row level security;
alter table public.ventas    enable row level security;

-- Refuerzo: se quitan también los permisos de tabla a los roles de la API pública.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on all tables    in schema public from anon, authenticated';
    execute 'revoke all on all sequences in schema public from anon, authenticated';
  end if;
end $$;